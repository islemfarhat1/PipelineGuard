"""
Explain PipelineGuard findings with a local Ollama model.

Advisory only. This command never prints PASS or BLOCK and its exit code
does not reflect findings: the V2 engine (security-v2.yml) decides.

Example:
    python -m assistant.explain --semgrep reports/semgrep.json \\
        --gitleaks reports/gitleaks.json --output explanations.md
"""

import argparse
import json
from dataclasses import dataclass

from engine.models import SecurityFinding
from assistant.client import DEFAULT_OLLAMA_URL, OllamaClient
from assistant.prompt import LEVELS, RESPONSE_SCHEMA, SYSTEM_PROMPT, build_prompt
from assistant.sources import load_findings, read_code_context, redact

DEFAULT_MODEL = "qwen2.5:7b"
MAX_FIELD_LENGTH = 2000
TEXT_FIELDS = ("explanation", "risk", "fix")
LEVEL_FIELDS = ("false_positive_likelihood", "confidence")

ADVISORY_NOTICE = (
    "> **Advisory only.** These explanations are generated by a local LLM "
    "and can be wrong. They never change the PASS/BLOCK decision, which is "
    "taken only by the deterministic V2 engine. A likely false positive "
    "is a hint for a human reviewer, not an exception."
)


@dataclass
class Explanation:
    finding: SecurityFinding
    answer: dict | None
    error: str = ""


def validate_response(text: str, secrets: set[str]) -> dict:
    """Treat the model output as untrusted input and check it strictly."""

    data = json.loads(text)

    if not isinstance(data, dict):
        raise ValueError("LLM answer is not a JSON object")

    answer = {}

    for field in TEXT_FIELDS:
        value = data.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"LLM answer has no valid '{field}'")
        answer[field] = redact(value.strip(), secrets)[:MAX_FIELD_LENGTH]

    for field in LEVEL_FIELDS:
        value = data.get(field)
        if value not in LEVELS:
            raise ValueError(f"LLM answer has an invalid '{field}'")
        answer[field] = value

    return answer


def explain_findings(findings, client, repo_root, secrets, secret_locations):
    explanations = []

    for finding in findings:
        try:
            context = read_code_context(
                finding, repo_root, secrets, secret_locations
            )
            text = client.generate(
                SYSTEM_PROMPT, build_prompt(finding, context), RESPONSE_SCHEMA
            )
            explanations.append(
                Explanation(finding, validate_response(text, secrets))
            )
        except (OSError, ValueError) as error:
            # json.JSONDecodeError is a ValueError; network errors are
            # OSError. One bad answer must not hide the other findings.
            explanations.append(
                Explanation(finding, None, redact(str(error), secrets))
            )

    return explanations


def render_markdown(explanations, model: str) -> str:
    lines = [
        "# PipelineGuard — finding explanations",
        "",
        ADVISORY_NOTICE,
        "",
        f"Model: `{model}` (local Ollama) · Findings: {len(explanations)}",
        "",
    ]

    for index, item in enumerate(explanations, start=1):
        finding = item.finding
        lines += [
            f"## {index}. {finding.severity.value} · "
            f"{finding.scanner.value} · `{finding.identifier}`",
            "",
            f"**Location:** `{finding.location}`",
            "",
        ]

        if item.answer is None:
            lines += [
                f"_Explanation unavailable: {item.error}_",
                "",
            ]
            continue

        answer = item.answer
        lines += [
            f"**Explanation:** {answer['explanation']}",
            "",
            f"**Risk:** {answer['risk']}",
            "",
            f"**Suggested fix:** {answer['fix']}",
            "",
            f"**Possible false positive:** {answer['false_positive_likelihood']}"
            f" · **Model confidence:** {answer['confidence']}",
            "",
        ]

    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Explain PipelineGuard findings with a local LLM "
        "(advisory only, never a security decision)."
    )
    parser.add_argument("--semgrep", help="Semgrep JSON report")
    parser.add_argument("--gitleaks", help="Gitleaks JSON report")
    parser.add_argument("--trivy", help="Trivy JSON report")
    parser.add_argument("--repo-path", default=".",
                        help="Repository root used to read code context")
    parser.add_argument("--output", default="explanations.md")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--ollama-url", default=DEFAULT_OLLAMA_URL)
    parser.add_argument("--max-findings", type=int, default=20)
    args = parser.parse_args(argv)

    if not (args.semgrep or args.gitleaks or args.trivy):
        parser.error("give at least one of --semgrep, --gitleaks, --trivy")

    if args.max_findings < 1:
        parser.error("--max-findings must be at least 1")

    try:
        client = OllamaClient(args.model, args.ollama_url)
        findings, secrets, secret_locations = load_findings(
            args.semgrep, args.gitleaks, args.trivy
        )
    except (OSError, ValueError) as error:
        print(f"Cannot explain findings: {error}")
        return 2

    selected = findings[: args.max_findings]
    if len(findings) > len(selected):
        print(f"Explaining the first {len(selected)} of {len(findings)} findings.")

    explanations = explain_findings(
        selected, client, args.repo_path, secrets, secret_locations
    )

    with open(args.output, "w", encoding="utf-8") as output:
        output.write(render_markdown(explanations, args.model))

    failed = sum(1 for item in explanations if item.answer is None)
    print(
        f"Wrote {args.output}: {len(explanations) - failed} explained, "
        f"{failed} unavailable. Advisory only: no security decision taken."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
